#!/usr/bin/env node
/**
 * Worst-case "everything visible" frames: for each pair in composition.js,
 * our own scenes rendered live at their hold (followers, toast, sidebar)
 * with every other element as a labelled mock box, over a backdrop, plus a
 * report of the overlaps and placement breaks. Asked for by Rotom for AJ's
 * composition review (2026-10-28), after AJ found we never tested with chat
 * or music on screen.
 *
 * Usage:
 *   npm run motion:compose                       # every pair
 *   npm run motion:compose -- hype-train pig-chat
 *   npm run motion:compose -- --bg=frame.png     # a real OBS frame as backdrop
 *   npm run motion:compose -- --no-render        # reuse the last live renders
 *   npm run motion:compose -- --today            # the layout before Defiant's collision fixes
 *
 * Writes tools/motion-results-compose/<pair>.png and report.md. Report
 * only: these are OBS layout questions for design review, so it exits 0.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, resolve, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { launchBrowser } from '../lib/browser.js';
import { SCENARIOS } from './scenes.js';
import { PAIRS, elementsFor, overlaps, placementBreaks } from './composition.js';
import { config } from '../../src/config/config.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2);
const flags = Object.fromEntries(argv.filter(a => a.startsWith('--')).map(a => {
  const i = a.indexOf('=');
  return i === -1 ? [a.slice(2), true] : [a.slice(2, i), a.slice(i + 1)];
}));
const names = argv.filter(a => !a.startsWith('--'));
const today = !!flags.today;
const pairs = names.length ? PAIRS.filter(p => names.includes(p.name)) : PAIRS;
if (!pairs.length) {
  console.error(`Unknown pair(s): ${names.join(', ')}. Available: ${PAIRS.map(p => p.name).join(', ')}`);
  process.exit(2);
}

const RUN = 'compose-live';
const liveDir = resolve(__dirname, '..', `motion-results-${RUN}`);
const outDir = resolve(__dirname, '..', today ? 'motion-results-compose-today' : 'motion-results-compose');
mkdirSync(outDir, { recursive: true });

/** The keyframe closest to the middle of a scenario's hold. */
function holdShot(name) {
  const s = SCENARIOS.find(x => x.name === name);
  const span = s.keyframeSpanMs || s.captureMs;
  const [from, to] = s.checks?.design?.holdMs ?? [0, span];
  const mid = (from + Math.min(to, span)) / 2;
  const at = s.keyframes.map(k => k * span).sort((a, b) => Math.abs(a - mid) - Math.abs(b - mid))[0];
  return `${name}/seed-1/t${String(Math.round(at)).padStart(5, '0')}.png`;
}

// Render our scenes once, without the keep-out mocks (compose draws them)
const live = [...new Set(pairs.flatMap(p => elementsFor(p.ids).map(e => e.scenario).filter(Boolean)))];
if (live.length && !flags['no-render']) {
  execFileSync(process.execPath, [resolve(__dirname, 'run.js'), ...live, '--seeds=1', '--no-keepout', `--out=${RUN}`], { stdio: 'inherit' });
}

const dataUrl = (path) => `data:image/${extname(path).slice(1) || 'png'};base64,${readFileSync(path).toString('base64')}`;
const bgImage = flags.bg && existsSync(String(flags.bg)) ? dataUrl(String(flags.bg)) : null;
const W = config.design.canvas.width;
const H = config.design.canvas.height;
const chromeTop = Math.round(config.design.playerChromeTop * H);
const COLORS = { P: '#4da3ff', A: '#ffa31a', G: '#ff4fa3' };

const { browser } = await launchBrowser({ width: W, height: H });
const page = await browser.newPage();
await page.setViewport({ width: W, height: H, deviceScaleFactor: 1 });

const report = [
  '# Everything-visible frames',
  '',
  `Generated by \`npm run motion:compose\` from tools/motion/composition.js, ${today ? 'today\'s layout' : 'the layout after Defiant\'s collision fixes'}. Boxes are canvas px; MIU boxes are ±20px. Live: ${live.join(', ') || 'none'}.`,
  ''
];

for (const pair of pairs) {
  const els = elementsFor(pair.ids, { today });
  const shots = els.filter(e => e.scenario).map(e => {
    const p = resolve(liveDir, holdShot(e.scenario));
    if (!existsSync(p)) throw new Error(`Missing ${p}: run without --no-render`);
    return dataUrl(p);
  });
  const mocks = els.filter(e => !e.scenario).map(e => ({ ...e, color: COLORS[e.kind] }));
  await page.setContent(`<html><body style="margin:0;background:#1b1d22"><canvas id="c" width="${W}" height="${H}"></canvas></body></html>`);
  await page.evaluate(async ({ shots, mocks, bgImage, W, H, chromeTop, title }) => {
    const load = (src) => new Promise((ok, err) => { const i = new Image(); i.onload = () => ok(i); i.onerror = err; i.src = src; });
    const ctx = document.getElementById('c').getContext('2d');
    if (bgImage) ctx.drawImage(await load(bgImage), 0, 0, W, H);
    // Mocks first, then our scenes: the toast and goal bar sit high in OBS's Alerts
    ctx.font = '600 20px system-ui, sans-serif';
    for (const m of mocks) {
      const [x0, y0, x1, y1] = m.box;
      ctx.fillStyle = m.color + '40';
      ctx.fillRect(x0, y0, x1 - x0, y1 - y0);
      ctx.strokeStyle = m.color;
      ctx.lineWidth = 3;
      ctx.setLineDash(m.face ? [12, 6] : []);
      ctx.strokeRect(x0 + 1.5, y0 + 1.5, x1 - x0 - 3, y1 - y0 - 3);
      ctx.setLineDash([]);
    }
    for (const s of shots) ctx.drawImage(await load(s), 0, 0, W, H);
    // Labels last, so a live scene doesn't hide which mock sits under it
    // A label that would land on one already drawn moves down a row
    const placed = [];
    for (const m of mocks) {
      const [x0, y0] = m.box;
      const w = ctx.measureText(m.label).width + 12;
      let y = Math.max(y0, 0) + 4;
      while (placed.some(p => x0 + 4 < p.x + p.w && p.x < x0 + 4 + w && y < p.y + 26 && p.y < y + 26)) y += 28;
      placed.push({ x: x0 + 4, y, w });
      ctx.fillStyle = m.color;
      ctx.fillRect(x0 + 4, y, w, 26);
      ctx.fillStyle = '#000';
      ctx.fillText(m.label, x0 + 10, y + 20);
    }
    // Player controls and the title
    ctx.strokeStyle = '#ff3b30';
    ctx.lineWidth = 2;
    ctx.beginPath();
    ctx.moveTo(0, chromeTop);
    ctx.lineTo(W, chromeTop);
    ctx.stroke();
    ctx.fillStyle = 'rgba(0,0,0,0.6)';
    ctx.fillRect(0, H - 40, W, 40);
    ctx.fillStyle = '#fff';
    ctx.font = '600 22px system-ui, sans-serif';
    ctx.fillText(`${title}   (blue persistent, orange alert, pink gag, dashed camera, red line = player controls)`, 16, H - 13);
  }, { shots, mocks, bgImage, W, H, chromeTop, title: pair.title });
  const file = resolve(outDir, `${pair.name}.png`);
  await (await page.$('#c')).screenshot({ path: file });

  const hits = overlaps(els, pair.exclusive);
  const breaks = placementBreaks(els, config.design);
  const label = (id) => els.find(e => e.id === id).label;
  report.push(`## ${pair.title}`, '', `![${pair.name}](${pair.name}.png)`, '');
  if (!hits.length && !breaks.length) report.push('Nothing readable is covered.', '');
  for (const h of hits) report.push(`- **${label(h.a)}** and **${label(h.b)}** overlap at x ${h.box[0]}-${h.box[2]}, y ${h.box[1]}-${h.box[3]} (${h.area} px²)`);
  for (const b of breaks) report.push(`- **${b.rule}**: ${b.detail}`);
  report.push('');
  console.log(`${pair.name}: ${hits.length} overlaps, ${breaks.length} placement breaks`);
}

await browser.close();
writeFileSync(resolve(outDir, 'report.md'), report.join('\n'));
console.log(`Frames and report: ${outDir}`);
