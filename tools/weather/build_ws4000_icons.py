#!/usr/bin/env python3
"""Bake the WeatherStar 4000 icons into sprite strips for Exo-Cast.

AJ (2026-11-11): "the icons for the weather need to use the weather star
versions, and they need that pixel look". The icons are the fan redraws by
Charles Abel, Nick Smith (twcclassics.com) and Malek Masoud, as shipped in
netbymatt/ws4kp (server/images/icons). Like the Star4000 fonts they carry no
formal licence; AJ chose to bundle those with credit (2026-11-11), and the
same goes for these (src/weather/ws4000/CREDITS.md).

Each GIF becomes one PNG strip (frames side by side, RGBA) plus an entry in
src/weather/ws4000icons.js with its size, frame count and frame time.

    python3 tools/weather/build_ws4000_icons.py <ws4kp>/server/images/icons
"""
import json
import os
import sys

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(ROOT, 'src', 'weather', 'ws4000')

# icon set -> {our name: GIF path under the icons folder}
SETS = {
    'big': {
        'sun': 'current-conditions/Sunny.gif',
        'moon': 'current-conditions/Clear.gif',
        'mostlysun': 'current-conditions/Partly-Cloudy.gif',
        'partly': 'current-conditions/Partly-Cloudy.gif',
        'partlymoon': 'current-conditions/Mostly-Clear.gif',
        'mostlycloudy': 'current-conditions/Cloudy.gif',
        'cloudy': 'current-conditions/Cloudy.gif',
        'rain': 'current-conditions/Rain.gif',
        'showers': 'current-conditions/Shower.gif',
        'storm': 'current-conditions/Thunderstorm.gif',
        'snow': 'current-conditions/Heavy-Snow.gif',
        'flurries': 'current-conditions/Light-Snow.gif',
        'mix': 'current-conditions/Rain-Snow.gif',
        'fog': 'current-conditions/Fog.gif',
        'moon-new': 'moon-phases/New-Moon.gif',
        'moon-first': 'moon-phases/First-Quarter.gif',
        'moon-full': 'moon-phases/Full-Moon.gif',
        'moon-last': 'moon-phases/Last-Quarter.gif',
    },
    'small': {
        'sun': 'regional-maps/Sunny.gif',
        'moon': 'regional-maps/Clear-1992.gif',
        'mostlysun': 'regional-maps/Partly-Cloudy.gif',
        'partly': 'regional-maps/Partly-Cloudy.gif',
        'partlymoon': 'regional-maps/Partly-Cloudy-Night.gif',
        'mostlycloudy': 'regional-maps/Mostly-Cloudy-1994.gif',
        'cloudy': 'regional-maps/Cloudy.gif',
        'rain': 'regional-maps/Rain-1992.gif',
        'showers': 'regional-maps/Scattered-Showers-1994.gif',
        'storm': 'regional-maps/Thunderstorm.gif',
        'snow': 'regional-maps/Heavy-Snow-1994.gif',
        'flurries': 'regional-maps/Light-Snow.gif',
        'mix': 'regional-maps/Rain-Snow-1992.gif',
        'fog': 'regional-maps/Fog.gif',
    },
}


def frames(path):
    """Every frame as a full RGBA image (Pillow composites GIF frames on seek)."""
    im = Image.open(path)
    out = []
    for k in range(getattr(im, 'n_frames', 1)):
        im.seek(k)
        out.append(im.convert('RGBA'))
    return out, max(60, im.info.get('duration') or 130)


def main(src):
    os.makedirs(OUT, exist_ok=True)
    done = {}
    manifest = {}
    for set_name, icons in SETS.items():
        manifest[set_name] = {}
        for name, rel in icons.items():
            if rel not in done:
                fr, ms = frames(os.path.join(src, rel))
                w, h = fr[0].size
                strip = Image.new('RGBA', (w * len(fr), h), (0, 0, 0, 0))
                for k, f in enumerate(fr):
                    strip.paste(f, (k * w, 0))
                file = (set_name + '-' + os.path.basename(rel)[:-4]).lower() + '.png'
                strip.save(os.path.join(OUT, file), optimize=True)
                done[rel] = {'file': file, 'w': w, 'h': h, 'n': len(fr), 'ms': ms if len(fr) > 1 else 0}
            manifest[set_name][name] = done[rel]
    files = sorted({v['file'] for v in done.values()})
    lines = [
        '// Generated by tools/weather/build_ws4000_icons.py: do not edit.',
        '// The WeatherStar 4000 icons as sprite strips (credits: ws4000/CREDITS.md).',
        '// Each URL is a literal new URL(), so Vite inlines the PNG into the build.',
        '',
        'const URLS = {',
    ]
    lines += [f"    '{f}': new URL('./ws4000/{f}', import.meta.url).href," for f in files]
    lines += ['};', '', '/** Icon sets: big (pages) and small (table rows), by icon kind. */',
              'export const WS_ICONS = ' + json.dumps(manifest, indent=4).replace('"', "'") + ';', '',
              '/** The URL of a strip file. */',
              'export const wsIconUrl = (file) => URLS[file];', '']
    with open(os.path.join(ROOT, 'src', 'weather', 'ws4000icons.js'), 'w') as fh:
        fh.write('\n'.join(lines))
    print(len(files), 'strips')


if __name__ == '__main__':
    main(sys.argv[1])
