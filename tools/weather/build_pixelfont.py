#!/usr/bin/env python3
"""
Bake the Star4000 face into a fixed bitmap font for Exo-Cast:
src/weather/pixelfont.js. AJ (2026-11-11): the text needs "that pixel
look", then "The pixelation isn't good, its too random": shrinking the
TTF and cutting its alpha drew the same letter differently every time.
A glyph baked once on the face's own grid looks the same everywhere.

The TTF is a smoothed trace of the WeatherStar's bitmap, monospaced at
973 units. A grid search over cell sizes and offsets (least partly-covered
cells over A-Z and 0-9) puts it at 12 columns per advance and 17 rows to
cap height, x offset 0.875 cell: about square pixels of 81 x 84 units.
Each cell is on when the outline covers half of it.

    pip install fonttools pillow numpy
    python3 tools/weather/build_pixelfont.py path/to/Star4000.ttf
"""
import sys
import numpy as np
from PIL import Image, ImageDraw
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen
from fontTools.pens.boundsPen import BoundsPen

COLS, ROWS, ABOVE, BELOW, OX, OY, R = 12, 17, 1, 4, 0.875, 0.0, 4


class PolyPen(BasePen):
    def __init__(self, gs):
        super().__init__(gs)
        self.polys, self.cur = [], []

    def _moveTo(self, p):
        self.cur = [p]

    def _lineTo(self, p):
        self.cur.append(p)

    def _curveToOne(self, a, b, c):
        p0 = self.cur[-1]
        for k in range(1, 9):
            u = k / 8
            self.cur.append(tuple((1 - u) ** 3 * p0[i] + 3 * (1 - u) ** 2 * u * a[i] + 3 * (1 - u) * u * u * b[i] + u ** 3 * c[i] for i in (0, 1)))

    def _qCurveToOne(self, a, b):
        p0 = self.cur[-1]
        for k in range(1, 9):
            u = k / 8
            self.cur.append(tuple((1 - u) ** 2 * p0[i] + 2 * (1 - u) * u * a[i] + u * u * b[i] for i in (0, 1)))

    def _closePath(self):
        self.polys.append(self.cur)
        self.cur = []

    _endPath = _closePath


def main(path):
    t = TTFont(path)
    cmap = t.getBestCmap()
    gs = t.getGlyphSet()
    adv = t['hmtx'][cmap[ord('H')]][0]
    bp = BoundsPen(gs)
    gs[cmap[ord('H')]].draw(bp)
    cap = bp.bounds[3]
    H, W, base = int(cap * 1.7 / R), int(adv / R) + 4, int(cap * 1.3 / R)
    ux, uy = adv / COLS / R, cap / ROWS / R
    chars = [chr(c) for c in range(0x21, 0x7f)] + ['°', '·']
    out = {}
    for ch in chars:
        if ord(ch) not in cmap:
            continue
        pen = PolyPen(gs)
        gs[cmap[ord(ch)]].draw(pen)
        a = np.zeros((H, W), dtype=bool)
        for poly in pen.polys:
            m = Image.new('1', (W, H), 0)
            ImageDraw.Draw(m).polygon([(x / R, base - y / R) for x, y in poly], fill=1)
            a ^= np.array(m, dtype=bool)
        rows = []
        for j in range(ROWS + ABOVE - 1, -BELOW - 1, -1):
            r = 0
            for i in range(-1, COLS):
                x0 = max(0, int((i + OX) * ux))
                x1 = max(x0 + 1, int((i + 1 + OX) * ux))
                y1 = int(base - (j + OY) * uy)
                y0 = max(0, int(base - (j + 1 + OY) * uy))
                c = a[y0:y1, x0:x1].mean() if y1 > y0 and x1 > x0 else 0
                r = (r << 1) | (1 if c >= 0.5 else 0)
            rows.append(r)
        out[ch] = rows
    lines = [
        '// Generated by tools/weather/build_pixelfont.py from Star4000.ttf: do not edit.',
        '// Each glyph is ROWS+ABOVE+BELOW rows, top first; each row a bitmask of',
        '// COLS+1 cells, leftmost cell in the highest bit.',
        f'export const PIXEL_FONT = {{ cols: {COLS + 1}, advance: {COLS}, cap: {ROWS}, above: {ABOVE}, below: {BELOW} }};',
        'export const GLYPHS = {',
    ]
    for ch, rows in out.items():
        key = repr(ch) if ch not in ("'", '\\') else ('"\'"' if ch == "'" else "'\\\\'")
        lines.append(f'    {key}: [{", ".join(str(r) for r in rows)}],')
    lines.append('};')
    open('src/weather/pixelfont.js', 'w').write('\n'.join(lines) + '\n')
    print(f'{len(out)} glyphs')


main(sys.argv[1])
