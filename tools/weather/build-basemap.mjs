// Builds src/weather/basemap.js: the radar page's map, drawn by the page
// itself (2026-11-10). CARTO's free dark tiles began stamping "API KEY
// REQUIRED", and a flat map with state lines is the 90s broadcast look
// anyway. Sources are public domain (US Census via us-atlas, Natural Earth
// via world-atlas):
//   curl -O https://cdn.jsdelivr.net/npm/us-atlas@3.0.1/states-10m.json
//   curl -O https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-50m.json
//   node tools/weather/build-basemap.mjs states-10m.json countries-50m.json
import { readFileSync, writeFileSync } from 'node:fs';

const [statesPath, countriesPath] = process.argv.slice(2);
if (!statesPath || !countriesPath) {
    console.error('usage: node tools/weather/build-basemap.mjs states-10m.json countries-50m.json');
    process.exit(1);
}

// Lower 48 plus the neighbours a regional view can reach
const BOX = { w: -128, e: -64, s: 22, n: 52 };
const TOL = 0.02;                       // degrees: about 2 px at the closest zoom (7)
const SKIP_STATES = new Set(['02', '15', '60', '66', '69', '72', '78']);
const NEIGHBOURS = new Set(['124', '484', '192', '044']);   // Canada, Mexico, Cuba, Bahamas

function decodeArcs(topo) {
    const [sx, sy] = topo.transform.scale;
    const [tx, ty] = topo.transform.translate;
    return topo.arcs.map((arc) => {
        let x = 0;
        let y = 0;
        return arc.map(([dx, dy]) => {
            x += dx;
            y += dy;
            return [x * sx + tx, y * sy + ty];
        });
    });
}

function ring(arcs, idx) {
    const out = [];
    for (const i of idx) {
        const a = i < 0 ? arcs[~i].slice().reverse() : arcs[i];
        out.push(...(out.length ? a.slice(1) : a));
    }
    return out;
}

function polygons(geom) {
    if (geom.type === 'Polygon') return [geom.arcs];
    if (geom.type === 'MultiPolygon') return geom.arcs;
    return [];
}

function simplify(pts, tol) {
    if (pts.length < 4) return pts;
    const [fx, fy] = pts[0];
    const [lx, ly] = pts[pts.length - 1];
    if (fx === lx && fy === ly) {
        // A closed ring has no chord to measure from: split it at the point
        // farthest from its start and simplify each half
        let far = 1;
        for (let i = 1; i < pts.length; i++) {
            if (Math.hypot(pts[i][0] - fx, pts[i][1] - fy) > Math.hypot(pts[far][0] - fx, pts[far][1] - fy)) far = i;
        }
        return [...simplify(pts.slice(0, far + 1), tol).slice(0, -1), ...simplify(pts.slice(far), tol)];
    }
    const keep = new Uint8Array(pts.length);
    keep[0] = keep[pts.length - 1] = 1;
    const stack = [[0, pts.length - 1]];
    while (stack.length) {
        const [a, b] = stack.pop();
        const [ax, ay] = pts[a];
        const [bx, by] = pts[b];
        const len = Math.hypot(bx - ax, by - ay) || 1e-9;
        let worst = -1;
        let at = -1;
        for (let i = a + 1; i < b; i++) {
            const d = Math.abs((bx - ax) * (ay - pts[i][1]) - (ax - pts[i][0]) * (by - ay)) / len;
            if (d > worst) { worst = d; at = i; }
        }
        if (worst > tol) {
            keep[at] = 1;
            stack.push([a, at], [at, b]);
        }
    }
    return pts.filter((_, i) => keep[i]);
}

function inBox(r) {
    return r.some(([x, y]) => x >= BOX.w && x <= BOX.e && y >= BOX.s && y <= BOX.n);
}

function build(topo, objName, pick) {
    const arcs = decodeArcs(topo);
    const out = [];
    for (const g of topo.objects[objName].geometries) {
        if (!pick(g)) continue;
        for (const poly of polygons(g)) {
            const rings = poly.map((idx) => simplify(ring(arcs, idx), TOL)).filter((r) => r.length >= 4);
            if (!rings.length || !inBox(rings[0])) continue;
            // Flat [lon, lat, lon, lat, ...] at 0.01 degrees (about 1 px at zoom 7)
            out.push(rings.map((r) => r.flatMap(([x, y]) => [Math.round(x * 100) / 100, Math.round(y * 100) / 100])));
        }
    }
    return out;
}

const states = build(JSON.parse(readFileSync(statesPath, 'utf8')), 'states', (g) => !SKIP_STATES.has(g.id));
const near = build(JSON.parse(readFileSync(countriesPath, 'utf8')), 'countries', (g) => NEIGHBOURS.has(g.id));
const body = `// Generated by tools/weather/build-basemap.mjs: do not edit by hand.
// The radar page's map: polygons as rings of flat [lon, lat, ...] pairs.
// US states (lower 48) from the US Census and the neighbouring countries
// from Natural Earth, both public domain.
export const STATES = ${JSON.stringify(states)};
export const NEIGHBOURS = ${JSON.stringify(near)};
`;
writeFileSync(new URL('../../src/weather/basemap.js', import.meta.url), body);
console.log(`states ${states.length} polygons, neighbours ${near.length}, ${(body.length / 1024).toFixed(0)} KB`);
